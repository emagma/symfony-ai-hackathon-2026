/**
 * `castor mcp:sylius-api-routes`: regenerates the route table at the end of
 * packages/mcp-sylius-bundle/docs/developer-guide.md from the API Platform
 * configuration of each Sylius tag (sparse clones, nothing installed). Run it
 * when a Sylius line is added or a new minor ships:
 *
 *   castor mcp:sylius-api-routes                        # the tags below
 *   TAGS="v1.14.20 v2.3.1" castor mcp:sylius-api-routes
 *
 * The hand-written part of the document (above the marker) is kept; the
 * generated part (below it) is replaced.
 *
 * Two steps per tag: the admin operations are read from the resource XML of
 * the ApiBundle (API Platform 2.7 metadata for 1.14, resources-3.0 for 2.x),
 * then the resource x line table and the differences between consecutive
 * lines are written.
 */

