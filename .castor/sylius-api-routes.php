/**
 * @param array<string, list<array<string, mixed>>> $opsPerLine
 */
function api_routes_table(array $opsPerLine): string
{
    $versions = array_keys($opsPerLine);
    $versions = array_map('strval', $versions);
    usort($versions, static fn (string $a, string $b): int => api_compare(array_map('intval', explode('.', $a)), array_map('intval', explode('.', $b))));

    // Per line: "<method>\0<masked path>" => [method, masked path, ops]
    $data = [];
    foreach ($versions as $v) {
        $m = [];
        $add = static function (string $method, string $path, array $op) use (&$m): void {
            $key = $method . "\0" . $path;
            $m[$key] ??= [$method, $path, []];
            $m[$key][2][] = $op;
        };
        foreach ($opsPerLine[$v] as $o) {
            $add(str_replace('(NOT EXPOSED)', '', $o['method']), api_mask(api_clean($o['path'])), $o);
        }
        foreach (API_EXTRA as [$method, $path, $source]) {
            $add($method, api_mask($path), ['path' => $path, 'op' => $source, 'method' => $method, 'kind' => 'symfony-route', 'norm' => [], 'denorm' => [], 'input' => null]);
        }
        // Zone.xml members_get_subresource / ZoneMember.xml api_zones_members_get_subresource: no
        // explicit path on either side; APIP 2.7 derives it; tests/Api/Admin/ZonesTest uses
        // /api/v2/admin/zones/%s/members
        if ('1.14' === $v) {
            $add('GET', '/admin/zones/{*}/members', ['path' => '/admin/zones/{code}/members [subresource, derived]', 'op' => 'members_get_subresource', 'method' => 'GET', 'kind' => 'subresource', 'norm' => ['admin:zone_member:show', 'sylius:admin:zone_member:show'], 'denorm' => [], 'input' => null]);
        }
        $data[$v] = $m;
    }

    $groupNames = array_column(API_GROUPS, 0);
    $rows = [];
    foreach ($data as $m) {
        foreach ($m as $key => [$method, $path]) {
            $rows[$key] = [$method, $path];
        }
    }
    $rows = array_values($rows);
    usort($rows, static fn (array $a, array $b): int => api_compare(
        [(int) array_search(api_group_of($a[1]), $groupNames, true), $a[1], $a[0]],
        [(int) array_search(api_group_of($b[1]), $groupNames, true), $b[1], $b[0]],
    ));

    $lines = [];
    $lines[] = "## Route table (admin, method x path template, per line)\n";
    $lines[] = 'Markers: `[default]` = no explicit path/uriTemplate in the XML, derived from `route_prefix`/`routePrefix` + shortName + identifier (verified against `tests/Api/Admin` of the tag, the 1.14 `paths_to_hide` list or the local shop\'s router cache unless noted); `[resource-level]` = `uriTemplate` set on the `<resource>` element and inherited; `[subresource]` = APIP 2.7 `<subresourceOperation>`; `(GetCollection)` = APIP 3 operation class for the translation rows. **NotExposed** = APIP `NotExposed` operation: the route exists for IRI generation but answers 404 (`NotExposedAction`).' . "\n";
    $previous = null;
    foreach ($rows as [$method, $path]) {
        $group = api_group_of($path);
        if ($group !== $previous) {
            $lines[] = "\n### $group\n";
            $lines[] = '| Method | 1.14 | 2.0 | 2.1 | 2.2 | 2.3 |';
            $lines[] = '|---|---|---|---|---|---|';
            $previous = $group;
        }
        $cells = array_map(static fn (string $v): string => api_cell($data[$v], $method, $path), $versions);
        $lines[] = '| ' . $method . ' | ' . implode(' | ', $cells) . ' |';
    }

    $lines[] = "\n## Differences between consecutive lines (computed)\n";
    $notExposed = static fn (array $o): string => str_contains($o['method'], 'NOT EXPOSED') ? ' **NotExposed (404)**' : '';
    $byKey = static fn (string $x, string $y): int => strcmp($x, $y);
    for ($i = 0; $i + 1 < \count($versions); ++$i) {
        [$a, $b] = [$versions[$i], $versions[$i + 1]];
        [$A, $B] = [$data[$a], $data[$b]];
        $lines[] = "### $a -> $b\n";
        $removed = array_keys(array_diff_key($A, $B));
        $added = array_keys(array_diff_key($B, $A));
        usort($removed, $byKey);
        usort($added, $byKey);
        $lines[] = \sprintf('Tier (b), URI variables masked: removed %d, added %d.', \count($removed), \count($added)) . "\n";
        foreach ($removed as $key) {
            $o = $A[$key][2][0];
            $lines[] = \sprintf('- REMOVED %s `%s`%s (%s)', $A[$key][0], api_clean($o['path']), $notExposed($o), api_str($o['op']));
        }
        foreach ($added as $key) {
            $o = $B[$key][2][0];
            $lines[] = \sprintf('- ADDED %s `%s`%s (%s)', $B[$key][0], api_clean($o['path']), $notExposed($o), api_str($o['op']));
        }

        $common = array_keys(array_intersect_key($A, $B));
        usort($common, $byKey);
        $renamed = [];
        foreach ($common as $key) {
            $pa = api_clean($A[$key][2][0]['path']);
            $pb = api_clean($B[$key][2][0]['path']);
            if ($pa !== $pb) {
                $renamed[] = [$A[$key][0], $pa, $pb];
            }
        }
        usort($renamed, api_compare(...));
        $lines[] = "\nTier (a), same route but URI variable renamed: " . \count($renamed) . ".\n";
        foreach ($renamed as [$method, $pa, $pb]) {
            $lines[] = "- $method `$pa` -> `$pb`";
        }

        $changed = [];
        foreach ($common as $key) {
            $oa = $A[$key][2][0];
            $ob = $B[$key][2][0];
            $ga = [api_sorted_set($oa['norm']), api_sorted_set($oa['denorm']), $oa['input'] ?? null];
            $gb = [api_sorted_set($ob['norm']), api_sorted_set($ob['denorm']), $ob['input'] ?? null];
            if ($ga !== $gb) {
                $changed[] = [$key, $ga, $gb];
            }
        }
        $lines[] = "\nSame route, normalization/denormalization groups or input class changed: " . \count($changed) . ".\n";
        if ('1.14' === $a) {
            $lines[] = '(1.14 -> 2.0: every common route changes groups because the legacy unprefixed `admin:*` names are dropped and the operation names change from `admin_*` to `sylius_api_admin_*`; not listed individually.)';
        } else {
            foreach ($changed as [$key, $ga, $gb]) {
                $lines[] = \sprintf('- %s `%s`: %s -> %s', $A[$key][0], api_clean($A[$key][2][0]['path']), api_repr_tuple($ga), api_repr_tuple($gb));
            }
        }
        $lines[] = '';
    }

    return implode("\n", $lines) . "\n";
}

function api_clean(string $path): string
{
    $path = (string) preg_replace('/ \[.*\]$/', '', $path);

    return str_starts_with($path, '/') ? $path : '/' . $path;
}

function api_mask(string $path): string
{
    return (string) preg_replace('/\{[^}]+\}/', '{*}', $path);
}

function api_group_of(string $masked): string
{
    foreach (API_GROUPS as [$label, $pattern]) {
        if (1 === preg_match('~' . $pattern . '~', $masked)) {
            return $label;
        }
    }

    return 'Other';
}

/**
 * @param array<string, array{0: string, 1: string, 2: list<array<string, mixed>>}> $m
 */
function api_cell(array $m, string $method, string $path): string
{
    $key = $method . "\0" . $path;
    if (!isset($m[$key])) {
        return '-';
    }
    $o = $m[$key][2][0];
    $cell = '`' . api_clean($o['path']) . '`';
    if (str_contains($o['method'], 'NOT EXPOSED')) {
        $cell .= ' **NotExposed (404)**';
    }
    if (1 === preg_match('/\[(.*)\]$/', $o['path'], $match)) {
        $cell .= ' `[' . $match[1] . ']`';
    }
    $kind = $o['kind'] ?? null;
    if ('Translation resources' === api_group_of($path) && \is_string($kind) && '' !== $kind && !\in_array($kind, ['item', 'collection'], true)) {
        $cell .= " ($kind)";
    }

    return $cell;
}

/**
 * @param list<mixed> $values
 *
 * @return list<mixed>
 */
function api_sorted_set(array $values): array
{
    $values = array_values(array_unique($values, \SORT_STRING));
    usort($values, static fn (mixed $a, mixed $b): int => strcmp((string) $a, (string) $b));

    return $values;
}

/**
 * A value as the table has always printed it (None for null).
 */
function api_str(mixed $value): string
{
    return null === $value ? 'None' : (string) $value;
}

/**
 * The (norm, denorm, input) triple as the table has always printed it:
 * (['a', 'b'], [], None), strings single-quoted, backslashes doubled.
 *
 * @param array{0: list<mixed>, 1: list<mixed>, 2: mixed} $tuple
 */
function api_repr_tuple(array $tuple): string
{
    return '(' . implode(', ', array_map(api_repr(...), $tuple)) . ')';
}

function api_repr(mixed $value): string
{
    if (null === $value) {
        return 'None';
    }
    if (\is_array($value)) {
        return '[' . implode(', ', array_map(api_repr(...), $value)) . ']';
    }
    $value = (string) $value;
    $quote = str_contains($value, "'") && !str_contains($value, '"') ? '"' : "'";
    $escaped = preg_replace_callback('/[\\\\\x00-\x1f\x7f' . preg_quote($quote, '/') . ']/', static fn (array $m): string => match ($m[0]) {
        '\\' => '\\\\',
        "\n" => '\n',
        "\r" => '\r',
        "\t" => '\t',
        $quote => '\\' . $quote,
        default => \sprintf('\x%02x', \ord($m[0])),
    }, $value);

    return $quote . $escaped . $quote;
}

/**
 * @param list<\DOMElement> $elements
 */
function api_all_unnamed(array $elements): bool
{
    foreach ($elements as $element) {
        if (null !== api_attr($element, 'name')) {
            return false;
        }
    }

    return true;
}

/**
 * The ordering of the keys: element by element, strings by code point,
 * integers by value, a shorter prefix first.
 *
 * @param list<int|string> $a
 * @param list<int|string> $b
 */
function api_compare(array $a, array $b): int
{
    foreach ($a as $i => $x) {
        if (!\array_key_exists($i, $b)) {
            return 1;
        }
        $y = $b[$i];
        $order = \is_int($x) && \is_int($y) ? $x <=> $y : strcmp((string) $x, (string) $y);
        if (0 !== $order) {
            return $order;
        }
    }

    return \count($a) <=> \count($b);
}
