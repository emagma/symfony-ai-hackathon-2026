// Extraction: the admin operations of one tag's resource XML
// ---------------------------------------------------------------------------

/**
 * @return list<array<string, mixed>>
 */
function api_admin_operations(string $directory): array
{
    $ops = [];
    foreach (api_walk($directory) as $file) {
        $head = (string) file_get_contents($file, false, null, 0, 2000);
        if (str_contains($head, 'resources-3.0')) {
            array_push($ops, ...api_parse_3($file));
        } elseif (str_contains($head, 'schema/metadata')) {
            array_push($ops, ...api_parse_27($file));
        }
    }

    return array_values(array_filter($ops, static function (array $o): bool {
        $name = $o['op'] ?? '';

        return str_starts_with($o['path'], '/admin') || str_starts_with($name, 'admin_') || str_contains($name, '_admin_');
    }));
}

/**
 * The XML files of a directory the way the first generator walked it: a
 * directory's files in name order, then its subdirectories in the order the
 * filesystem lists them (symbolic links not followed).
 *
 * @return list<string>
 */
function api_walk(string $directory): array
{
    $files = [];
    $directories = [];
    foreach (scandir($directory, \SCANDIR_SORT_NONE) ?: [] as $entry) {
        if ('.' === $entry || '..' === $entry) {
            continue;
        }
        $path = "$directory/$entry";
        if (is_dir($path)) {
            if (!is_link($path)) {
                $directories[] = $path;
            }
        } elseif (str_ends_with($entry, '.xml')) {
            $files[] = $entry;
        }
    }
    sort($files, \SORT_STRING);

    $walked = array_map(static fn (string $file): string => "$directory/$file", $files);
    foreach ($directories as $path) {
        array_push($walked, ...api_walk($path));
    }

    return $walked;
}

function api_load(string $path): \DOMElement
{
    $dom = new \DOMDocument();
    if (!$dom->load($path) || null === $dom->documentElement) {
        throw new \RuntimeException("Unreadable XML: $path");
    }

    return $dom->documentElement;
}

function api_attr(\DOMElement $element, string $name): ?string
{
    return $element->hasAttribute($name) ? $element->getAttribute($name) : null;
}

/**
 * The direct children of an element with this namespace and local name.
 *
 * @return list<\DOMElement>
 */
function api_children(\DOMElement $element, string $ns, string $name): array
{
    $children = [];
    foreach ($element->childNodes as $child) {
        if ($child instanceof \DOMElement && $ns === $child->namespaceURI && $name === $child->localName) {
            $children[] = $child;
        }
    }

    return $children;
}

/**
 * The descendants with this namespace and local name, in document order.
 *
 * @return list<\DOMElement>
 */
function api_descendants(\DOMElement $element, string $ns, string $name): array
{
    return iterator_to_array($element->getElementsByTagNameNS($ns, $name), false);
}

/**
 * The text of an element before its first child element, trimmed.
 */
function api_text(\DOMElement $element): string
{
    $text = '';
    foreach ($element->childNodes as $child) {
        if ($child instanceof \DOMElement) {
            break;
        }
        if (\XML_TEXT_NODE === $child->nodeType || \XML_CDATA_SECTION_NODE === $child->nodeType) {
            $text .= $child->textContent;
        }
    }

    return trim($text);
}

/**
 * An API Platform 2.7 <attribute>: its text, a list of unnamed attributes, or
 * a map (\stdClass) of named ones.
 */
function api_attr_tree(\DOMElement $element): string|array|\stdClass
{
    $kids = api_children($element, API_NS27, 'attribute');
    if ([] === $kids) {
        return api_text($element);
    }
    if (api_all_unnamed($kids)) {
        return array_map(api_attr_tree(...), $kids);
    }
    $map = new \stdClass();
    $count = 0;
    foreach ($kids as $kid) {
        $key = api_attr($kid, 'name');
        $key = null === $key || '' === $key ? '_' . $count : $key;
        if (!property_exists($map, $key)) {
            ++$count;
        }
        $map->{$key} = api_attr_tree($kid);
    }

    return $map;
}

/**
 * The named <attribute> children of an element, by name.
 *
 * @return array<string, string|array<mixed>|\stdClass>
 */
function api_attributes(\DOMElement $element): array
{
    $attributes = [];
    foreach (api_children($element, API_NS27, 'attribute') as $attribute) {
        $attributes[(string) api_attr($attribute, 'name')] = api_attr_tree($attribute);
    }

    return $attributes;
}

/**
 * An API Platform 3 element: its <values> as a list or a map (\stdClass), or its text.
 */
function api_values3(\DOMElement $element): string|array|\stdClass
{
    $values = api_children($element, API_NS3, 'values')[0] ?? null;
    if (null === $values) {
        return api_text($element);
    }
    $kids = api_children($values, API_NS3, 'value');
    if (api_all_unnamed($kids)) {
        return array_map(api_values3(...), $kids);
    }
    $map = new \stdClass();
    foreach ($kids as $kid) {
        $map->{api_attr($kid, 'name') ?: '__none__'} = api_values3($kid);
    }

    return $map;
}

/**
 * @return list<mixed>
 */
function api_groups_of(mixed $context): array
{
    if ($context instanceof \stdClass) {
        $groups = $context->groups ?? null;
        if (\is_array($groups)) {
            return $groups;
        }
        if (\is_string($groups)) {
            return [$groups];
        }
    }

    return [];
}

function api_kebab_plural(string $short): string
{
    $s = strtolower((string) preg_replace('/(?<!^)(?=[A-Z])/', '-', $short));
    if (str_ends_with($s, 'y') && !str_contains('aeiou', substr($s, -2, 1))) {
        return substr($s, 0, -1) . 'ies';
    }
    foreach (['s', 'x', 'ch', 'sh'] as $end) {
        if (str_ends_with($s, $end)) {
            return $s . 'es';
        }
    }

    return $s . 's';
}

function api_default_path(string $prefix, string $short, bool $item): string
{
    $path = ('' !== $prefix ? '/' . trim($prefix, '/') : '') . '/' . api_kebab_plural($short);

    return $path . ($item ? '/{id}' : '') . ' [default]';
}

/**
 * @param list<mixed> $norm
 * @param list<mixed> $denorm
 *
 * @return array<string, mixed>
 */
function api_operation(?string $name, string $kind, string $method, string $path, array $norm, array $denorm, mixed $input): array
{
    return ['op' => $name, 'kind' => $kind, 'method' => strtoupper($method), 'path' => $path, 'norm' => $norm, 'denorm' => $denorm, 'input' => $input];
}

/**
 * API Platform 2.7 metadata (Sylius 1.14).
 *
 * @return list<array<string, mixed>>
 */
function api_parse_27(string $file): array
{
    $ops = [];
    foreach (api_descendants(api_load($file), API_NS27, 'resource') as $resource) {
        $short = (string) api_attr($resource, 'shortName');
        $attributes = api_attributes($resource);
        $routePrefix = $attributes['route_prefix'] ?? '';
        $routePrefix = \is_string($routePrefix) ? $routePrefix : '';
        $identifiers = [];
        foreach (api_children($resource, API_NS27, 'property') as $property) {
            if ('true' === api_attr($property, 'identifier')) {
                $identifiers[] = api_attr($property, 'name');
            }
        }
        $identifier = 1 === \count($identifiers) ? (string) $identifiers[0] : 'id';

        foreach (api_descendants($resource, API_NS27, 'subresourceOperation') as $sub) {
            $a = api_attributes($sub);
            if (isset($a['path']) && \is_string($a['path']) && '' !== $a['path']) {
                $method = $a['method'] ?? 'GET';
                $ops[] = api_operation(api_attr($sub, 'name'), 'subresource', \is_string($method) ? $method : 'GET', $a['path'] . ' [subresource]',
                    api_groups_of($a['normalization_context'] ?? null), [], null);
            }
        }

        foreach (['collection' => 'collectionOperation', 'item' => 'itemOperation'] as $kind => $tag) {
            foreach (api_descendants($resource, API_NS27, $tag) as $operation) {
                $a = api_attributes($operation);
                $method = $a['method'] ?? 'GET';
                $path = $a['path'] ?? null;
                if (null === $path) {
                    $path = str_replace('{id}', '{' . $identifier . '}', api_default_path($routePrefix, $short, 'item' === $kind));
                } elseif ('' !== $routePrefix) {
                    $path = '/' . trim($routePrefix, '/') . $path;
                }
                $input = $a['input'] ?? null;
                if ($input instanceof \stdClass) {
                    $input = $input->class ?? null;
                }
                $ops[] = api_operation(api_attr($operation, 'name'), $kind, \is_string($method) ? $method : 'GET', (string) $path,
                    api_groups_of($a['normalization_context'] ?? null),
                    api_groups_of($a['denormalization_context'] ?? null),
                    $input);
            }
        }
    }

    return $ops;
}

/**
 * API Platform 3 resources (Sylius 2.x).
 *
 * @return list<array<string, mixed>>
 */
function api_parse_3(string $file): array
{
    $ops = [];
    foreach (api_descendants(api_load($file), API_NS3, 'resource') as $resource) {
        $class = (string) api_attr($resource, 'class');
        $short = api_attr($resource, 'shortName');
        $routePrefix = api_attr($resource, 'routePrefix') ?? '';
        $resourceUri = api_attr($resource, 'uriTemplate');
        foreach (api_descendants($resource, API_NS3, 'operation') as $operation) {
            $klass = api_attr($operation, 'class') ?? '';
            $kshort = substr((string) strrchr('\\' . $klass, '\\'), 1);
            $method = api_attr($operation, 'method');
            $method = null !== $method && '' !== $method ? $method : (API_CLASS_METHOD[$kshort] ?? '?' . $klass);
            $path = api_attr($operation, 'uriTemplate');
            $prefix = api_attr($operation, 'routePrefix');
            $prefix = null !== $prefix && '' !== $prefix ? $prefix : $routePrefix;
            if (null === $path && null !== $resourceUri) {
                $path = $resourceUri . ' [resource-level]';
            } elseif (null === $path) {
                $name = api_attr($operation, 'shortName');
                if (null === $name || '' === $name) {
                    $name = null !== $short && '' !== $short ? $short : api_title(str_replace('_', ' ', (string) preg_replace('/^%sylius\.model\.(.*)\.class%$/', '$1', $class)));
                }
                $path = api_default_path($prefix, $name, !\in_array($kshort, ['GetCollection', 'Post'], true));
            } elseif ('' !== $prefix) {
                $path = '/' . trim($prefix, '/') . $path;
            }
            $normalization = api_children($operation, API_NS3, 'normalizationContext')[0] ?? null;
            $denormalization = api_children($operation, API_NS3, 'denormalizationContext')[0] ?? null;
            $ops[] = api_operation(api_attr($operation, 'name'), $kshort, $method, $path,
                null !== $normalization ? api_groups_of(api_values3($normalization)) : [],
                null !== $denormalization ? api_groups_of(api_values3($denormalization)) : [],
                api_attr($operation, 'input'));
        }
    }

    return $ops;
}

/**
 * Title case without spaces: each run of letters capitalised, the spaces removed.
 */
function api_title(string $words): string
{
    return str_replace(' ', '', (string) preg_replace_callback('/[A-Za-z]+/', static fn (array $m): string => ucfirst(strtolower($m[0])), $words));
}

