#[AsTask(name: 'sylius-api-routes', description: 'Regenerate the route table of the Sylius bundle developer guide from the Sylius tags (TAGS="v1.14.20 v2.3.1" to choose)')]
function sylius_api_routes(): void
{
    $doc = (string) file_get_contents(API_ROUTES_DOC);
    $lines = explode("\n", $doc);
    $at = array_search(API_ROUTES_MARKER, $lines, true);
    if (false === $at) {
        throw new \RuntimeException(\sprintf("No marker line in %s:\n    %s", API_ROUTES_DOC, API_ROUTES_MARKER));
    }

    $env = getenv('TAGS');
    $tags = preg_split('/\s+/', trim(false === $env || '' === trim($env) ? API_ROUTES_TAGS : $env), -1, \PREG_SPLIT_NO_EMPTY) ?: [];

    $work = sys_get_temp_dir() . '/sylius-api-routes-' . bin2hex(random_bytes(6));
    fs()->mkdir($work);

    try {
        $ops = [];
        foreach ($tags as $tag) {
            $line = (string) preg_replace('/^v([0-9]+\.[0-9]+).*/', '$1', $tag);
            io()->writeln("· $tag → $line");
            $clone = "$work/$tag";
            run(['git', '-c', 'advice.detachedHead=false', 'clone', '-q', '--depth', '1', '--branch', $tag, '--filter=blob:none', '--sparse', 'https://github.com/Sylius/Sylius.git', $clone]);
            run(['git', '-C', $clone, 'sparse-checkout', 'set', 'src/Sylius/Bundle/ApiBundle/Resources/config']);
            $config = "$clone/src/Sylius/Bundle/ApiBundle/Resources/config";
            $resources = is_dir("$config/api_platform/resources") ? "$config/api_platform/resources" : "$config/api_resources";
            $ops[$line] = api_admin_operations($resources);
        }
    } finally {
        fs()->remove($work);
    }

    $head = implode("\n", \array_slice($lines, 0, $at + 1)) . "\n";
    file_put_contents(API_ROUTES_DOC, $head . api_routes_table($ops));
    io()->writeln('✓ ' . realpath(API_ROUTES_DOC));
}

